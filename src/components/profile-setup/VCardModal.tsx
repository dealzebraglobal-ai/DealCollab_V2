'use client';
import React, { useMemo, useRef, useState } from 'react';
import Image from 'next/image';
import { X, Download, Share2, User, Phone, Mail, Building2, MapPin, Briefcase, Sparkles, AlertCircle, Check } from 'lucide-react';
import type { UserProfile } from '../UserProvider';

interface VCardModalProps {
  isOpen: boolean;
  onClose: () => void;
  data: UserProfile | null;
  isProfileComplete: boolean;
}

interface RequiredField {
  key: string;
  label: string;
  present: boolean;
}

function buildRequiredFields(data: UserProfile | null): RequiredField[] {
  const name = data?.fullName || data?.name;
  const role = data?.role === 'Other' ? data?.customRole : data?.role;
  const company = data?.firmName || data?.companyName;
  const place = data?.baseCity || data?.base_city;
  const sectors = data?.sectors || data?.priority_sectors;

  return [
    { key: 'name', label: 'Full Name', present: !!name },
    { key: 'phone', label: 'Contact Number', present: !!data?.phone },
    { key: 'email', label: 'Email', present: !!data?.email },
    { key: 'company', label: 'Company Name', present: !!company },
    { key: 'role', label: 'Profession', present: !!role },
    { key: 'place', label: 'Place', present: !!place },
    { key: 'sectors', label: 'Interested Sector', present: !!(sectors && sectors.length > 0) },
  ];
}

// Escapes text per RFC 6350 (vCard 4.0) — commas, semicolons and backslashes are
// structural delimiters in the format and must be escaped in field values.
export function vcardEscape(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/,/g, '\\,').replace(/;/g, '\\;').replace(/\n/g, '\\n');
}

export function buildVCardText(input: {
  name: string;
  phone: string | null;
  email: string;
  company: string | null;
  role: string | null;
  place: string | null;
  sectors: string[];
}): string {
  const lines = [
    'BEGIN:VCARD',
    'VERSION:3.0',
    `FN:${vcardEscape(input.name)}`,
    `N:${vcardEscape(input.name)};;;;`,
  ];
  if (input.company) lines.push(`ORG:${vcardEscape(input.company)}`);
  if (input.role) lines.push(`TITLE:${vcardEscape(input.role)}`);
  if (input.phone) lines.push(`TEL;TYPE=CELL:${vcardEscape(input.phone)}`);
  lines.push(`EMAIL:${vcardEscape(input.email)}`);
  if (input.place) lines.push(`ADR;TYPE=WORK:;;;${vcardEscape(input.place)};;;`);
  if (input.sectors.length > 0) {
    lines.push(`NOTE:Interested sectors: ${vcardEscape(input.sectors.join(', '))}. Via DealCollab.`);
  }
  lines.push('NOTE:Generated by DealCollab — the AI-driven M&A deal-sourcing platform.');
  lines.push('END:VCARD');
  return lines.join('\r\n');
}

export default function VCardModal({ isOpen, onClose, data, isProfileComplete }: VCardModalProps) {
  const [copyState, setCopyState] = useState<'idle' | 'copied'>('idle');
  const cardRef = useRef<HTMLDivElement>(null);

  const fields = useMemo(() => buildRequiredFields(data), [data]);
  const missing = fields.filter(f => !f.present);
  const canRender = isProfileComplete && missing.length === 0;

  const name = data?.fullName || data?.name || '';
  const role = data?.role === 'Other' ? data?.customRole : data?.role;
  const company = data?.firmName || data?.companyName;
  const place = [data?.baseCity || data?.base_city, data?.baseCountry || data?.base_country].filter(Boolean).join(', ');
  const sectors = data?.sectors || data?.priority_sectors || [];
  const photo = data?.profileImage || data?.profile_image || data?.userAvatar;

  if (!isOpen) return null;

  const vcardText = canRender
    ? buildVCardText({
      name,
      phone: data?.phone || null,
      email: data?.email || '',
      company: company || null,
      role: role || null,
      place: place || null,
      sectors,
    })
    : '';

  const handleDownload = () => {
    if (!canRender) return;
    const blob = new Blob([vcardText], { type: 'text/vcard;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${name.replace(/[^a-z0-9]+/gi, '_') || 'dealcollab'}.vcf`;
    document.body.appendChild(a);
    a.click();
    a.remove();
    URL.revokeObjectURL(url);
  };

  const handleShare = async () => {
    if (!canRender) return;
    const shareText = `${name}${role ? ` — ${role}` : ''}${company ? ` @ ${company}` : ''}\nPhone: ${data?.phone}\nEmail: ${data?.email}${place ? `\nBased in: ${place}` : ''}\n\nShared via DealCollab`;
    try {
      if (navigator.share) {
        await navigator.share({ title: `${name} — DealCollab vCard`, text: shareText });
        return;
      }
      throw new Error('Web Share API unavailable');
    } catch {
      try {
        await navigator.clipboard.writeText(shareText);
        setCopyState('copied');
        setTimeout(() => setCopyState('idle'), 2000);
      } catch {
        // Clipboard unavailable too — the card is still visible/downloadable, so this is a soft failure.
      }
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-sm animate-in fade-in duration-200" onClick={onClose}>
      <div
        className="relative w-full max-w-md bg-white rounded-3xl shadow-2xl border border-gray-100 overflow-hidden flex flex-col max-h-[90vh] animate-in zoom-in-95 duration-200"
        onClick={(e) => e.stopPropagation()}
      >
        <div className="flex items-center justify-between p-5 border-b border-gray-100">
          <h2 className="text-base font-black text-gray-900 tracking-tight">Your vCard</h2>
          <button onClick={onClose} className="w-8 h-8 rounded-full bg-gray-100 hover:bg-gray-200 text-gray-500 hover:text-gray-900 flex items-center justify-center transition-all">
            <X size={16} />
          </button>
        </div>

        <div className="p-5 overflow-y-auto space-y-5">
          {!canRender ? (
            <div className="p-5 rounded-2xl bg-amber-50 border border-amber-200 space-y-3">
              <div className="flex items-center gap-2 text-amber-800 font-bold text-sm">
                <AlertCircle size={16} />
                Complete your profile to activate your vCard
              </div>
              <ul className="space-y-1.5">
                {missing.map(f => (
                  <li key={f.key} className="flex items-center gap-2 text-xs text-amber-700 font-medium">
                    <span className="w-1.5 h-1.5 rounded-full bg-amber-400 shrink-0" />
                    {f.label} is missing
                  </li>
                ))}
              </ul>
              {!isProfileComplete && missing.length === 0 && (
                <p className="text-xs text-amber-700 font-medium">Finish onboarding to unlock your vCard.</p>
              )}
            </div>
          ) : (
            <>
              {/* The card itself */}
              <div ref={cardRef} className="rounded-3xl bg-gradient-to-br from-[#0B1B2B] to-[#111827] p-6 text-white relative overflow-hidden shadow-xl">
                <div className="absolute top-0 right-0 w-40 h-40 bg-[#F97316]/20 rounded-full -mr-16 -mt-16 blur-3xl pointer-events-none" />
                <div className="relative z-10 flex items-center gap-2 mb-5">
                  <div className="bg-[#F97316] text-white p-1 rounded shadow-lg">
                    <Sparkles size={12} />
                  </div>
                  <span className="text-[10px] font-black uppercase tracking-[0.2em] text-white/70">DealCollab</span>
                </div>

                <div className="relative z-10 flex items-center gap-4">
                  <div className="w-16 h-16 rounded-2xl bg-white/10 border border-white/10 flex items-center justify-center overflow-hidden shrink-0 relative">
                    {photo ? (
                      <Image src={photo} alt={name} fill sizes="64px" className="object-cover" />
                    ) : (
                      <User size={28} className="text-white/70" />
                    )}
                  </div>
                  <div className="min-w-0">
                    <p className="text-lg font-black tracking-tight truncate">{name}</p>
                    {role && <p className="text-xs font-semibold text-white/70 truncate">{role}</p>}
                    {company && <p className="text-xs font-medium text-white/50 truncate">{company}</p>}
                  </div>
                </div>

                <div className="relative z-10 mt-5 space-y-2 border-t border-white/10 pt-4">
                  <div className="flex items-center gap-2 text-xs font-medium text-white/80">
                    <Phone size={12} className="text-[#F97316]" /> {data?.phone}
                  </div>
                  <div className="flex items-center gap-2 text-xs font-medium text-white/80">
                    <Mail size={12} className="text-[#F97316]" /> {data?.email}
                  </div>
                  {place && (
                    <div className="flex items-center gap-2 text-xs font-medium text-white/80">
                      <MapPin size={12} className="text-[#F97316]" /> {place}
                    </div>
                  )}
                  {company && (
                    <div className="flex items-center gap-2 text-xs font-medium text-white/80">
                      <Building2 size={12} className="text-[#F97316]" /> {company}
                    </div>
                  )}
                </div>

                {sectors.length > 0 && (
                  <div className="relative z-10 mt-4 flex flex-wrap gap-1.5">
                    {sectors.slice(0, 4).map(s => (
                      <span key={s} className="flex items-center gap-1 px-2 py-0.5 bg-white/10 rounded-full text-[10px] font-bold text-white/80">
                        <Briefcase size={9} /> {s}
                      </span>
                    ))}
                  </div>
                )}
              </div>

              <div className="grid grid-cols-2 gap-3">
                <button
                  onClick={handleDownload}
                  className="flex items-center justify-center gap-2 py-3 bg-[#1F2937] hover:bg-[#F97316] text-white rounded-xl text-xs font-bold uppercase tracking-wider transition-all"
                >
                  <Download size={14} /> Download
                </button>
                <button
                  onClick={handleShare}
                  className="flex items-center justify-center gap-2 py-3 bg-white border border-gray-200 hover:border-[#F97316] hover:text-[#F97316] text-gray-700 rounded-xl text-xs font-bold uppercase tracking-wider transition-all"
                >
                  {copyState === 'copied' ? <><Check size={14} /> Copied</> : <><Share2 size={14} /> Share</>}
                </button>
              </div>
            </>
          )}
        </div>
      </div>
    </div>
  );
}
